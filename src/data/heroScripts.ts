const MAP = new Map<string, HeroEpisodeScript>();
for (const [videoId, heroId, mood, location, withSuwan, suwanOutfit, beats, choice] of RAW) {
  MAP.set(videoId, { videoId, heroId, mood, location, withSuwan, suwanOutfit, beats, choice });
}

export function getHeroScript(videoId: string): HeroEpisodeScript | null {
  return MAP.get(videoId) ?? null;
}

export function speakerLabel(script: HeroEpisodeScript, beat: ScriptBeat): string {
  if (beat.speaker === 'narrator') return '';
  if (beat.speaker === 'suwan') return '苏晚';
  if (beat.speaker === 'hero') return heroById(script.heroId).name;
  return beat.speakerName ?? '路人';
}
